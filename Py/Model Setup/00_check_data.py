"""##Helper Functions"""

def run_path(cfg, *parts):
    """Path inside the run folder. Creates the parent folder."""
    path = os.path.join(cfg["run_dir"], *parts)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    return path


def copy_to_local(path):
    """Copy a file from Drive to Colab's own disk once per session (reading a big csv from Drive is slow)."""
    import shutil
    local = os.path.join("/content", os.path.basename(path))
    if not os.path.exists(local):
        shutil.copy(path, local)
    return local


def check_compendium(df):
    """Print basic checks on a genes x samples compendium.

    Returns, for each sample, the fraction of genes sitting at that sample's minimum value
    (zero counts all end up as the same value within a sample).
    """
    vals = df.values
    print("genes x samples:", df.shape)
    print("value range:", float(np.nanmin(vals)), "to", float(np.nanmax(vals)))
    print("missing values:", int(np.isnan(vals).sum()))
    print("duplicate gene ids:", int(df.index.duplicated().sum()), "| duplicate sample ids:", int(df.columns.duplicated().sum()))
    at_floor = (vals == vals.min(axis=0)).mean(axis=0)
    print(f"samples with more than half their genes at their own minimum: {int((at_floor > 0.5).sum())} of {df.shape[1]}")
    # SeqAdage clips its noisy copy of the data to 0-1 but never checks the range, so I check it here
    assert vals.min() >= -0.01 and vals.max() <= 1.01, "values are not roughly between 0 and 1, so the data isn't scaled the way SeqAdage expects"
    return at_floor


def plot_data(df, at_floor, path, n_values=1_000_000, seed=0):
    """Histogram of a random sample of compendium values, and of the per-sample fraction of genes at the minimum."""
    r = np.random.default_rng(seed)
    vals = df.values
    pick = vals[r.integers(0, vals.shape[0], n_values), r.integers(0, vals.shape[1], n_values)]
    fig, ax = plt.subplots(1, 2, figsize=(10, 3.5))
    ax[0].hist(pick, bins=50)
    ax[0].set_xlabel("expression value (scaled)")
    ax[0].set_ylabel("count (random sample of entries)")
    ax[1].hist(at_floor, bins=50)
    ax[1].set_xlabel("fraction of genes at the sample's minimum")
    ax[1].set_ylabel("samples")
    plt.tight_layout()
    fig.savefig(path, dpi=120)
    plt.show()
    print("saved", path)

