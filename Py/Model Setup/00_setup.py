for file, changes in FIXES.items():
    path = os.path.join("seqADAGE", file)
    text = open(path).read()
    for old, new in changes:
        if new not in text:
            assert text.count(old) == 1, f"can't find the line to change in {file}: {old.strip()}"
            text = text.replace(old, new)
    open(path, "w").write(text)
print("encoder activation fix in place:", "activation=act1" in open("seqADAGE/Py/adage/LinkedAE.py").read())

