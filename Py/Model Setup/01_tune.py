"""## Helper Functions"""

def run_path(cfg, *parts):
    """Path inside the run folder. Creates the parent folder."""
    path = os.path.join(cfg["run_dir"], *parts)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    return path


def hparams_path(cfg):
    return run_path(cfg, "tuning", "best_hparams.json")


def copy_to_local(path):
    """Copy a file from Drive to Colab's own disk once per session (reading a big csv from Drive is slow)."""
    import shutil
    local = os.path.join("/content", os.path.basename(path))
    if not os.path.exists(local):
        shutil.copy(path, local)
    return local


def redirect_tuner(SeqAdage, directory, max_epochs):
    """Make SeqAdage.tune_model save its Hyperband search in `directory` with `max_epochs`.

    This only changes the keras_tuner that the SeqAdage module sees, not the keras_tuner package itself.
    """
    import keras_tuner

    def hyperband(**kwargs):
        kwargs.update(directory=directory, max_epochs=max_epochs)
        return keras_tuner.Hyperband(**kwargs)

    SeqAdage.keras_tuner = types.SimpleNamespace(HyperParameters=keras_tuner.HyperParameters, Hyperband=hyperband)


def trials_table(tuner):
    """One row per trial: its hyperparameters, score (validation loss), and rank. Same columns as the lab's tuner notebooks."""
    rows = []
    for rank, trial in enumerate(tuner.oracle.get_best_trials(num_trials=len(tuner.oracle.trials))):
        rows.append(trial.hyperparameters.get_config()["values"] |
                    {"Score": trial.score, "Trial ID": trial.trial_id, "Best step": trial.best_step, "rank": rank})
    return pd.DataFrame(rows)


def plot_trials(df, path):
    """Validation loss of every trial against each hyperparameter that was actually searched."""
    searched = [k for k in ["dropout", "init", "kl1", "kl2", "lr", "bs", "mm", "units", "act1", "act2", "shuffle"]
                if k in df and df[k].nunique() > 1]
    fig, ax = plt.subplots(1, max(len(searched), 1), figsize=(3 * max(len(searched), 1), 3), squeeze=False)
    for a, k in zip(ax[0], searched):
        x = df[k].astype(str) if df[k].dtype == object or df[k].dtype == bool else df[k]
        a.scatter(x, df["Score"], s=10, c=df["rank"], cmap="viridis_r")
        a.set_xlabel(k)
        a.set_yscale("log")
    ax[0][0].set_ylabel("validation loss (lower is better)")
    plt.tight_layout()
    fig.savefig(path, dpi=120)
    plt.show()
    print("saved", path)

