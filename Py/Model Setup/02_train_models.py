"""## Helper Function"""

def group_seed(cfg, g, i):
    """Seed for model i of group g. Groups use consecutive blocks of seeds, so no two models share a seed."""
    return cfg["base_seed"] + g * cfg["models_per_group"] + i


def task_to_model(cfg, task):
    """Turn a model number (0 to n_groups * models_per_group - 1) into (group, index in group).

    Model numbers are also what the Slurm array index will be on the cluster.
    """
    n = cfg["n_groups"] * cfg["models_per_group"]
    if not 0 <= task < n:
        raise ValueError(f"model number {task} is out of range, it has to be between 0 and {n - 1}")
    return divmod(task, cfg["models_per_group"])


def run_path(cfg, *parts):
    """Path inside the run folder. Creates the parent folder."""
    path = os.path.join(cfg["run_dir"], *parts)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    return path


def model_path(cfg, g, seed):
    return run_path(cfg, "models", f"group{g}", f"model_seed{seed}.npz")


def hparams_path(cfg):
    return run_path(cfg, "tuning", "best_hparams.json")


def load_hparams(cfg, use_default):
    """Hyperparameters from the tuner (tuning/best_hparams.json), or the default_hparams in the settings cell with use_default=True."""
    if use_default:
        print("WARNING: using the default hyperparameters from the settings cell, not the tuned ones")
        return dict(cfg["default_hparams"])
    path = hparams_path(cfg)
    if not os.path.exists(path):
        raise FileNotFoundError(f"{path} doesn't exist. Run 01_tune.ipynb first, or set DEFAULT_HPARAMS = True.")
    with open(path) as f:
        return json.load(f)


def load_model(path):
    """Load a saved model (individual or eADAGE) as a dict of arrays."""
    with np.load(path, allow_pickle=False) as z:
        return {k: z[k] for k in z.files}

def copy_to_local(path):
    """Copy a file from Drive to Colab's own disk once per session (reading a big csv from Drive is slow)."""
    import shutil
    local = os.path.join("/content", os.path.basename(path))
    if not os.path.exists(local):
        shutil.copy(path, local)
    return local

def train_one(SeqAdage, cfg, hp, seed):
    """Train one model with SeqAdage and return (the SeqAdage object, seconds it took)."""
    import keras
    keras.utils.set_random_seed(seed)  # weight initialization; train_model seeds the noise itself
    sa = SeqAdage.SeqAdage(cfg["data_path"], seed=seed, enc_dim=hp["units"], kl1=hp["kl1"], kl2=hp["kl2"],
                           act=hp["act1"], act2=hp["act2"], tied=True, epochs=cfg["epochs"], init=hp["init"],
                           batch_size=hp["bs"], dropout=hp["dropout"], mm=hp["mm"], lr=hp["lr"], v=2)
    start = time.time()
    # NOTE: train_model fits x=clean data, y=noisy data (the reverse of a denoising autoencoder and of tune_model).
    # I'm leaving the lab code as it is until I've asked Prof. Doing about it.
    sa.train_model()
    return sa, time.time() - start

def train_and_save(SeqAdage, cfg, hp, task, force=False):
    """Train model number `task` and save it. Skips it if it's already saved (unless force=True)."""
    import keras
    g, i = task_to_model(cfg, task)
    seed = group_seed(cfg, g, i)
    path = model_path(cfg, g, seed)
    if os.path.exists(path) and not force:
        print(f"group {g} model {i} (seed {seed}) is already saved, skipping")
        return
    print(f"training group {g} model {i}, seed {seed}")
    sa, secs = train_one(SeqAdage, cfg, hp, seed)

    act = sa.autoencoder.dense_1.activation.__name__
    assert act == hp["act1"], (f"the encoder's activation is {act}, not {hp['act1']}: "
                               "check that 00_setup.ipynb applied the encoder-activation fix")

    W, eb, db = sa.autoencoder.get_weights()[:3]
    loss, val_loss = np.array(sa.history.history["loss"]), np.array(sa.history.history["val_loss"])
    np.savez(path, W=W, eb=eb, db=db, act1=hp["act1"], act2=hp["act2"], loss=loss, val_loss=val_loss, seed=seed, group=g,
             hparams=json.dumps(hp), train_seconds=secs)

    lab_dir = os.path.dirname(run_path(cfg, "models", "lab_format", "x"))
    for folder in ["weights", "bias", "loss", "val_loss"]:
        os.makedirs(os.path.join(lab_dir, folder), exist_ok=True)
    sa.save_weights(lab_dir, f"ad_g{g}_{seed}")
    keras.backend.clear_session()
    print(f"group {g} model {i} seed {seed}: loss {loss[0]:.4f} -> {loss[-1]:.4f}, "
          f"val_loss {val_loss[0]:.4f} -> {val_loss[-1]:.4f}, {secs / 60:.1f} min")

def check_training(cfg):
    """Loss curves of every saved model, the spread of final validation losses, and a list of missing models."""
    models, missing = [], []
    for g in range(cfg["n_groups"]):
        for i in range(cfg["models_per_group"]):
            seed = group_seed(cfg, g, i)
            path = model_path(cfg, g, seed)
            if os.path.exists(path):
                models.append(load_model(path))
            else:
                missing.append((g, i, g * cfg["models_per_group"] + i))
    print(f"{len(models)} models saved, {len(missing)} missing")
    if missing:
        print("missing (group, index, array task):", missing)
    if not models:
        raise RuntimeError("nothing to plot yet")

    fig, ax = plt.subplots(1, 3, figsize=(15, 3.8))
    for m in models:
        ax[0].plot(m["loss"], color="orange", lw=0.8, alpha=0.6)
        ax[0].plot(m["val_loss"], color="red", lw=0.8, alpha=0.6)
    ax[0].set(title="loss (orange: training, red: validation)", xlabel="epoch", ylabel="MSE")
    final = np.array([m["val_loss"][-1] for m in models])
    ax[1].hist(final, bins=20)
    ax[1].set(title="final validation loss", xlabel="MSE", ylabel="models")
    for m in models[:3]:
        ax[2].hist(m["W"].ravel(), bins=100, histtype="step", density=True, label=f"seed {int(m['seed'])}")
    ax[2].set(title="encoder weights", yscale="log")
    ax[2].legend(fontsize=7)
    plt.tight_layout()
    fig.savefig(run_path(cfg, "training_check.png"), dpi=120)
    plt.show()
    print("saved", run_path(cfg, "training_check.png"))

    print(f"final val_loss: min {final.min():.4f}, median {np.median(final):.4f}, max {final.max():.4f}")
    print(f"epoch 1 -> last epoch (median): loss {np.median([m['loss'][0] for m in models]):.4f} -> "
          f"{np.median([m['loss'][-1] for m in models]):.4f}, val_loss {np.median([m['val_loss'][0] for m in models]):.4f} -> "
          f"{np.median(final):.4f}")
    print(f"training time per model: median {np.median([m['train_seconds'] for m in models]) / 60:.1f} min")
    # a model whose loss went up or became nan probably diverged (e.g. learning rate too high)
    bad = [int(m["seed"]) for m in models if not np.isfinite(m["val_loss"][-1]) or m["loss"][-1] > m["loss"][0]]
    if bad:
        print("WARNING: these seeds ended with a higher loss than they started with, or nan:", bad)

